/**
 * Writes Cloudflare Pages routing files from config/site-routing.mjs (MIG-30 / QUI-247):
 *   public/_redirects  — same 301s as next.config.ts redirects()
 *   public/_headers    — same security headers as next.config.ts headers()
 * Run: node scripts/generate-pages-files.mjs (also part of `prebuild`).
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { REDIRECT_PAIRS, SECURITY_HEADERS, sourceVariants } from '../config/site-routing.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const header = '# Generated by scripts/generate-pages-files.mjs from config/site-routing.mjs — do not edit by hand.\n';

const redirectLines = REDIRECT_PAIRS.flatMap(([from, to]) =>
  sourceVariants(from).map((src) => `${src} ${to} 301`)
);
writeFileSync(join(root, 'public', '_redirects'), `${header}${redirectLines.join('\n')}\n`, 'utf8');

const headerLines = ['/*', ...SECURITY_HEADERS.map(({ key, value }) => `  ${key}: ${value}`)];
writeFileSync(join(root, 'public', '_headers'), `${header}${headerLines.join('\n')}\n`, 'utf8');

console.log(`_redirects (${redirectLines.length} rules) + _headers (${SECURITY_HEADERS.length} headers) updated`);
